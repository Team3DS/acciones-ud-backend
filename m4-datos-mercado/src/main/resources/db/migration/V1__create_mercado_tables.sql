CREATE TABLE historico_cotizacion (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR2(20) NOT NULL,
    open NUMBER(19,4) NOT NULL,
    high NUMBER(19,4) NOT NULL,
    low NUMBER(19,4) NOT NULL,
    close NUMBER(19,4) NOT NULL,
    volume NUMBER NOT NULL,
    timestamp TIMESTAMP NOT NULL,
    intervalo VARCHAR2(10) NOT NULL
);

CREATE TABLE horario_mercado (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mercado_mic VARCHAR2(20) NOT NULL,
    dia_semana NUMBER NOT NULL,
    apertura TIMESTAMP NOT NULL,
    cierre TIMESTAMP NOT NULL,
    pre_market TIMESTAMP,
    after_hours TIMESTAMP
);
