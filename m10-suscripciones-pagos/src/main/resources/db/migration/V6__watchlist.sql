CREATE TABLE watchlist_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    symbol VARCHAR(20) NOT NULL,
    agregado_en TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_watchlist_usuario_simbolo UNIQUE (user_id, symbol),
    CONSTRAINT ck_watchlist_simbolo CHECK (symbol = upper(btrim(symbol)))
);

CREATE INDEX idx_watchlist_usuario ON watchlist_item (user_id, agregado_en);
