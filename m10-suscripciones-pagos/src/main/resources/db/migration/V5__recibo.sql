CREATE TABLE recibo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suscripcion_id BIGINT NOT NULL REFERENCES suscripcion (id),
    stripe_invoice_id VARCHAR(100) NOT NULL UNIQUE,
    numero VARCHAR(50),
    monto NUMERIC(19, 2) NOT NULL,
    moneda CHAR(3) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    intento INT NOT NULL DEFAULT 0,
    periodo_inicio TIMESTAMPTZ,
    periodo_fin TIMESTAMPTZ,
    url_recibo TEXT,
    url_pdf TEXT,
    emitido_en TIMESTAMPTZ NOT NULL,
    pagado_en TIMESTAMPTZ,
    actualizado_en TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_recibo_monto CHECK (monto >= 0),
    CONSTRAINT ck_recibo_moneda CHECK (moneda = 'USD'),
    CONSTRAINT ck_recibo_estado CHECK (estado IN ('ABIERTO', 'PAGADO', 'FALLIDO', 'ANULADO', 'INCOBRABLE')),
    CONSTRAINT ck_recibo_intento CHECK (intento >= 0)
);

CREATE INDEX idx_recibo_suscripcion ON recibo (suscripcion_id, emitido_en DESC);
